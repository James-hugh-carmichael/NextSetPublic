export function normalizeGenre(genre: string) {
  return genre.toLocaleLowerCase().replace(/[^a-z0-9]/g, "");
}

export function genresMatch(firstGenre: string, secondGenre: string) {
  return normalizeGenre(firstGenre) === normalizeGenre(secondGenre);
}
